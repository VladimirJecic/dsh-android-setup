TAG_RE = re.compile(r"<[^>]+>")
WORD_RE = re.compile(r"[A-Za-zÄÖÜäöüß]+")


# ------------------------------------------------- spoljni dodaci (JSON) ------
# Rečnik se od epizode 13 dopunjuje iz JSON-a, da se ova skripta više ne
# patch-uje (orijenti za ubacivanje su se pomerali i lomili).
#
#   ~/.dsh/skills/partial-prevod/lexikon.json  -> trajni dodaci, sve epizode
#   <folder epizode>/lexikon_dodaci.json       -> dodaci samo za tu epizodu
#
# Format (svi ključevi su opcioni):
#   {"LEX": {"waisen": "die Waise = siroče"}, "REFL": {...}, "CASE_NOUNS": {...},
#    "PREP": {...}, "SKIP": ["gral"], "A1": ["lange"], "STOP": ["je"],
#    "NAMES": ["carlo"]}
def _primeni_dodatke():
    import json
    putanje = [os.path.join(os.path.dirname(os.path.abspath(__file__)),
                            "lexikon.json")]
    if len(sys.argv) > 1:
        putanje.append(os.path.join(
            os.path.dirname(os.path.abspath(sys.argv[1])), "lexikon_dodaci.json"))
    ukupno = 0
    for p in putanje:
        if not os.path.exists(p):
            continue
        try:
            with open(p, encoding="utf-8") as fh:
                d = json.load(fh)
        except (ValueError, OSError) as e:
            print(f"UPOZORENJE: ne mogu da učitam {p}: {e}")
            continue
        LEX.update(d.get("LEX", {}))
        REFL.update(d.get("REFL", {}))
        CASE_NOUNS.update(d.get("CASE_NOUNS", {}))
        PREP.update(d.get("PREP", {}))
        for ime, tabela in (("SKIP", SKIP), ("A1", A1), ("STOP", STOP),
                            ("NAMES", NAMES)):
            tabela.update(d.get(ime, []))
        n = sum(len(v) for v in d.values())
        ukupno += n
        if n:
            print(f"dodaci iz {os.path.basename(p)}: {n}")
    if ukupno:
        print(f"rečnik posle dodataka: LEX {len(LEX)}, A1 {len(A1)}, "
              f"SKIP {len(SKIP)}, REFL {len(REFL)}")


_primeni_dodatke()


def parse_srt(text):
    out = []
    for block in text.strip().split("\n\n"):
        parts = block.split("\n")
        if len(parts) < 3 or "-->" not in parts[1]:
            continue
        out.append((parts[0].strip(), parts[1].strip(), parts[2:]))
    return out


def plain(lines):
    return TAG_RE.sub("", " ".join(lines)).strip()


def srt_to_ass_time(ts):
    h, m, rest = ts.split(":")
    s, ms = rest.split(",")
    return f"{int(h)}:{int(m):02d}:{int(s):02d}.{int(ms)//10:02d}"


def count_sentences(text):
    """Rough sentence count: terminal punctuation followed by space+capital."""
    return len(re.findall(r"[.!?…]+(?:\s|$)", text))


def lemma_keys(entry):
    """Possible base forms of a lexicon entry, for the A1/SKIP filter.

    The filter must not depend on the surface form: 'gekommen' is listed in LEX
    as 'kommen = doći', and 'kommen' is A1, so 'gekommen' has to be skipped too.
    """
    head = entry.split(" = ")[0].strip().lower()
    keys = {head, head.split()[-1]}
    for art in ("der ", "die ", "das ", "sich ", "zu ", "im ", "am "):
        if head.startswith(art):
            keys.add(head[len(art):])
    return keys


def collect(text):
    """Split this line's translatable words into content words and prepositions."""
    content, preps, seen = [], [], set()
    # "sich erfreuen" znaci "uzivati", a golo "erfreuen" "obradovati" -- zato se
    # REFL tabela koristi samo kad je u bloku stvarno prisutna rec "sich".
    has_sich = bool(re.search(r"\bsich\b", text, re.I))
    for m in WORD_RE.finditer(text):
        w = m.group(0)
        lw = w.lower()
        if lw in NAMES or lw in STOP or lw in SKIP or lw in A1:
            continue
        entry = REFL.get(lw) if has_sich else None
        if not entry:
            entry = CASE_NOUNS.get(lw) if w[0].isupper() else None
        if not entry:
            entry = LEX.get(lw)
        is_prep = False
        if not entry:
            entry = PREP.get(lw)
            is_prep = bool(entry)
        if not entry:
            continue
        # filter on the base form, so inflected A1 words are skipped as well
        if lemma_keys(entry) & (A1 | SKIP):
            continue
        display = entry.split(" = ")[0]
        if display in seen:
            continue
        seen.add(display)
        (preps if is_prep else content).append(entry)
    return content, preps


MAX_CHARS = 84


def key_words(text, recent, idx, per_row=4, src_rows=1):
    """Return a list of rows, each with up to `per_row` 'word = prevod' items.

    Content words (nouns, verbs, adjectives) come first in order of
    appearance; prepositions then fill the leftover slots, at most one per row
    so they never crowd out the content words.  A second row is used when the
    line has more material than fits in one row, or when it holds more than one
    sentence.
    """
    content, preps = collect(text)

    # recency filter, with a fallback so a line never loses its key words
    def fresh(items):
        out = [c for c in items if recent.get(c.split(" = ")[0], -99) <= idx - 6]
        return out if out else items

    content, preps = fresh(content), fresh(preps)

    # The vocabulary row mirrors the source subtitle: a second row is used only
    # when the original subtitle itself is wrapped over two lines, or when it
    # holds more than one sentence.  A single-line subtitle stays a single row
    # of four words so the frame is not covered in text.
    two_rows = count_sentences(text) > 1 or src_rows >= 2
    max_rows = 2 if two_rows else 1
    slots = per_row * max_rows

    # chunk the content words into rows, then give each row at most one
    # preposition in whatever space is left
    # A row may hold at most `per_row` items; when a second row is available it
    # may also hold at most MAX_CHARS characters, so a row of long entries does
    # not wrap over three visual lines and cover the picture.
    rows = []
    for item in content[:slots]:
        target = None
        for row in rows:                      # fill row 1 first, then row 2
            if len(row) >= per_row:
                continue
            width = sum(len(x) for x in row) + 2 * len(row)
            if row and max_rows > 1 and width + len(item) > MAX_CHARS:
                continue
            target = row
            break
        if target is not None:
            target.append(item)
        elif len(rows) < max_rows:
            rows.append([item])
        else:
            # No row has room inside the width budget.  Space is nicer, but a
            # lost word is worse: fall back to the old packing for this item --
            # into the emptiest row, so the overflow stays as small as possible.
            room = [r for r in rows if len(r) < per_row]
            if room:
                min(room, key=lambda r: sum(len(x) for x in r) + 2 * len(r)
                    ).append(item)
            else:
                rows[-1].append(item)
    if not rows:
        rows.append([])

    while len(rows) < max_rows:
        rows.append([])
    # At most one preposition per row, and only into leftover space.  Rows are
    # filled from the last one backwards so a preposition sits next to the
    # content words instead of jumping into the first row and pushing a content
    # word down.  A preposition is dropped only when no row has room left.
    used = set()
    for p in preps:
        best = None
        for ri in reversed(range(len(rows))):
            row = rows[ri]
            if ri in used or len(row) >= per_row:
                continue
            width = sum(len(x) for x in row) + (2 * len(row) if row else 0)
            if row and max_rows > 1 and width + 2 + len(p) > MAX_CHARS:
                continue
            best = ri
            break
        if best is None:
            # the width budget leaves no room, but dropping a preposition is
            # worse than a row that wraps -- use the old rule then, again into
            # the emptiest row
            room = [ri for ri in range(len(rows))
                    if ri not in used and len(rows[ri]) < per_row]
            if room:
                best = min(room, key=lambda ri: sum(len(x) for x in rows[ri])
                           + 2 * len(rows[ri]))
        if best is None:
            break
        rows[best].append(p)
        used.add(best)

    rows = [r for r in rows if r]
    for r in rows:
        for e in r:
            recent[e.split(" = ")[0]] = idx
    return rows


def main():
    src = sys.argv[1] if len(sys.argv) > 1 else None
    if not src:
        print("usage: generate_partial_srt.py <input.srt> [out_basename]")
        sys.exit(1)
    base = sys.argv[2] if len(sys.argv) > 2 else "partial-prevod"
    outdir = os.path.dirname(os.path.abspath(src))

    raw = open(src, encoding="utf-8").read()
    entries = parse_srt(raw)

    recent, srt_parts, ass_events, gaps, n_vocab = {}, [], [], [], 0

    for i, (no, ts, lines) in enumerate(entries):
        ger = plain(lines)
        italic = any("<i>" in l for l in lines)
        src_rows = len([l for l in lines if l.strip()])
        rows = key_words(ger, recent, i, src_rows=src_rows)
        if rows:
            n_vocab += 1
        else:
            gaps.append((no, ts, ger))

        # one text block, rows separated by a hard line break
        vocab_text = "\\N".join(", ".join(r) for r in rows)

        start, end = [t.strip() for t in ts.split("-->")]
        # ---- SRT: vocab event pinned to top with \an8, dialogue at bottom
        if rows:
            srt_parts.append(f"{len(srt_parts)+1}\n{ts}\n{{\\an8}}{vocab_text}")
        srt_parts.append(f"{len(srt_parts)+1}\n{ts}\n{ger}")

        # ---- ASS: two styles, precise top / bottom placement
        if rows:
            ass_events.append(
                f"Dialogue: 0,{srt_to_ass_time(start)},{srt_to_ass_time(end)},"
                f"Vocab,,0,0,0,,{vocab_text}")
        ger_ass = f"{{\\i1}}{ger}{{\\i0}}" if italic else ger
        ass_events.append(
            f"Dialogue: 0,{srt_to_ass_time(start)},{srt_to_ass_time(end)},"
            f"Default,,0,0,0,,{ger_ass}")

    srt_path = os.path.join(outdir, base + ".srt")
    with open(srt_path, "w", encoding="utf-8") as fh:
        fh.write("\n\n".join(srt_parts) + "\n")

    ass_path = os.path.join(outdir, base + ".ass")
    header = """[Script Info]
ScriptType: v4.00+
PlayResX: 852
PlayResY: 480
WrapStyle: 0
ScaledBorderAndShadow: yes

[V4+ Styles]
Format: Name, Fontname, Fontsize, PrimaryColour, SecondaryColour, OutlineColour, BackColour, Bold, Italic, Underline, StrikeOut, ScaleX, ScaleY, Spacing, Angle, BorderStyle, Outline, Shadow, Alignment, MarginL, MarginR, MarginV, Encoding
Style: Vocab,DejaVu Sans,17,&H0000E6FF,&H000000FF,&H00000000,&H96000000,-1,0,0,0,100,100,0,0,1,2,1,8,40,40,12,1
Style: Default,DejaVu Sans,24,&H00FFFFFF,&H000000FF,&H00000000,&H96000000,0,0,0,0,100,100,0,0,1,2,1,2,25,25,24,1

[Events]
Format: Layer, Start, End, Style, Name, MarginL, MarginR, MarginV, Effect, Text
"""
    with open(ass_path, "w", encoding="utf-8") as fh:
        fh.write(header + "\n".join(ass_events) + "\n")

    print(f"blocks           : {len(entries)}")
    print(f"with vocabulary  : {n_vocab}")
    print(f"without          : {len(gaps)}")
    print(f"wrote            : {srt_path}")
    print(f"wrote            : {ass_path}")
    if gaps:
        print("\n--- blocks with no key word (extend lexicon if important) ---")
        for no, ts, g in gaps:
            print(f"  [{no}] {g}")


if __name__ == "__main__":
    main()
